# Import system libraries
import numpy as np

# Global variables
App_Name = 'SiNaMG'
App_Vers = '0.0.1'
grid_id = 1
out_file = 0
OS_newline = "\n" #Linux
# OS_newline = "\r\n" # Windows

#::::::::::::::::::::::::::::::::::::::::::::::::::
def ncomment():
    l = '$'
    return l

#::::::::::::::::::::::::::::::::::::::::::::::::::
def nline(st):
    l = '{0:<80s}'.format(st)+OS_newline
    return l

#::::::::::::::::::::::::::::::::::::::::::::::::::
def txt_field(st):
    l = '{0:<8s}'.format(st)
    return l
def txt_2fields(st):
    l = '{0:<16s}'.format(st)
    return l

#::::::::::::::::::::::::::::::::::::::::::::::::::
def num_field(st):
    l = '{0:>8s}'.format(st)
    return l
def nas_int(n):
    l = '{:d}'.format(n)
    return l
def nas_float(n):
    s = np.format_float_scientific(n,unique=False,precision=4,exp_digits=1,pad_left=0)
    if (len(s)>9):
        dig = len(s)-9
        s = np.format_float_scientific(n,unique=False,precision=4-dig,exp_digits=1,pad_left=0)
    l = s.replace('e','')
    return l

#::::::::::::::::::::::::::::::::::::::::::::::::::
def nheader():
    l = nline(ncomment()+' Generated by {0} - NASTRAN Interface Vers. {1}'.format(App_Name,App_Vers))
    l = l +nline(ncomment()+' Nastran input deck ')
    l = l +nline('SOL 103')
    l = l +nline('CEND')
    l = l +nline(ncomment())
    l = l +nline('BEGIN BULK')
    l = l +nline(ncomment())
    return l

#::::::::::::::::::::::::::::::::::::::::::::::::::
def nfoot():
    l = nline('ENDDATA')
    return l

#::::::::::::::::::::::::::::::::::::::::::::::::::
def grid_header(g_dic):
    fam = nas_int( g_dic['family'] )
    l = nline( txt_field(ncomment())+txt_2fields('grid data')+num_field(fam) )
    return l

#::::::::::::::::::::::::::::::::::::::::::::::::::
def grid_data(g_dic):
    global grid_id
    
    label = 'GRID'
    blank = num_field('0')

    gid = nas_int(grid_id)
    fam = nas_int(g_dic['family'])
    x = nas_float(g_dic['point'][0])
    y = nas_float(g_dic['point'][1])
    z = nas_float(g_dic['point'][2])

    s = nline( txt_field(label)+num_field(gid)+num_field(fam)+\
               num_field(x)+num_field(y)+num_field(z)+blank+num_field('')+blank )
    grid_id += 1
    return s

#::::::::::::::::::::::::::::::::::::::::::::::::::
def reset_grid_id():
    global grid_id
    grid_id = 1

#::::::::::::::::::::::::::::::::::::::::::::::::::
def norm_vec(ar):
    arn = ar/np.linalg.norm(ar)
    return arn
    
